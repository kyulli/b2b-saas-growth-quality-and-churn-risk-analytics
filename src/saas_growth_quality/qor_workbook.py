    rt.put(f"A{r + 1}", "Usage minus seat NRR (pp)"); rt.put(f"B{r + 1}", f"=E{usage_row}-E{seat_row}", PCT)
    rt.put(f"C{r + 1}", f"={B['bm_usage']}-{B['bm_seat']}", PCT); rt.put(f"D{r + 1}", "Benchmarkit 2026 gap in column C")
