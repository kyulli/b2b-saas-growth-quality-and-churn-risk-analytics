            rt.put(f"D{r}", round(v["grr"], 5), PCT); rt.put(f"E{r}", round(v["nrr"], 5), PCT); rt.put(f"F{r}", round(v["logo_churn"], 5), PCT)
            rt.put(f"G{r}", f"=D{r}-{B['sc_grr']}", PCT); rt.put(f"H{r}", f"=D{r}-{B['bm_grr']}", PCT); rt.put(f"I{r}", f"=E{r}-{B['sc_nrr']}", PCT)
