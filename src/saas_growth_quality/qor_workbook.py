    SC25 = "SaaS Capital 2025 retention benchmarks, >1,000 private B2B SaaS companies >$1M ARR, measured Dec 2023 to Dec 2024. https://www.saas-capital.com/wp-content/uploads/2025/09/RB32WS1-2025-B2B-SaaS-Retention-Benchmarks.pdf"
