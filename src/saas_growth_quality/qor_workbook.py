                                ("Retention", "12-month cohort GRR/NRR now (Jul 2025 to Jul 2026); monthly-compounding trap"),
                                ("Concentration", "Top-N ARR share, HHI, trend"), ("Revenue_to_Cash", "Revenue, invoicing, collections, AR, DSO"),
